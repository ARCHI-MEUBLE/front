/**
 * API Proxy - Samples analytics
 * Proxie vers le backend PHP pour les analytics des échantillons
 */
import type { NextApiRequest, NextApiResponse } from 'next';

import { backendHeaders, forwardSetCookies } from '@/lib/backendProxy';

const API_URL = (process.env.NEXT_PUBLIC_API_URL || 'http://127.0.0.1:8000');

export default async function handler(req: NextApiRequest, res: NextApiResponse) {
  try {
    const url = `${API_URL}/backend/api/admin/samples/analytics.php`;

    const response = await fetch(url, {
      method: req.method || 'GET',
      headers: {
        'Content-Type': 'application/json',
        ...backendHeaders(req),
      },
      credentials: 'include',
    });

    const data = await response.json();

    forwardSetCookies(res, response);
    res.status(response.status).json(data);
  } catch (error) {
    console.error('Samples analytics proxy error:', error);
    res.status(500).json({ error: 'Failed to fetch samples analytics' });
  }
}
